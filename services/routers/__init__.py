    """挂载已拆出的域路由（idempotent：可重复调用，但不推荐）。"""
    from services.routers import (
        animate,
        aria,
        auth,
        books,
        chemistry,
        cognitive,
        conic_geometry,
        cornell,
        cowriter,
        edu_assets,
        english_check,
        geometry,
        health,
        immersive,
        invitations,
        learning,
        memory,
        notebooks,
        insights,
        papers,
        parent,
        plan,
        pilot,
        product,
        operator,
        practice,
        progress,
        questions,
        reading,
        related_labs,
        research,
        review,
        socratic,
        starmap,
        subjects,
        textbook,
        viz,
        voice,
    )

    for mod in (
        health,
        memory,
        cornell,
        auth,
        aria,
        socratic,
        starmap,
        review,
        textbook,
        cognitive,
        invitations,
        papers,
        plan,
        insights,
        parent,
        practice,
        pilot,
        product,
        operator,
        progress,
        subjects,
        immersive,
        learning,
        geometry,
        conic_geometry,
        chemistry,
        english_check,
        edu_assets,
        related_labs,
        books,
        notebooks,
        cowriter,
        reading,
        animate,
        research,
        questions,
        viz,
        voice,
    ):
        app.include_router(mod.router)
